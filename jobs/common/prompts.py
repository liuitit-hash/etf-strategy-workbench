def system_for(btype: str) -> str:
    suffix = {"pre": SUFFIX_PRE, "intra": SUFFIX_INTRA,
              "post": SUFFIX_POST, "daily": SUFFIX_DAILY}[btype]
    return COMMON_PREFIX + suffix
